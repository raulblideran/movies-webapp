#!/usr/bin/env bash
# Build the cloud-init "User Data" for a new server. Paste/import the result into the provider's
# User Data box (IONOS: Advanced Options → User Data, type Cloud Config) when (re)installing
# Rocky/Alma/RHEL 9-10. The server then provisions itself completely on first boot.
#
#   ./deploy/build-cloud-init.sh            → deploy/secrets/cloud-init.yaml (contains secrets: git-ignored)
#
# Then run ./deploy/migrate.sh <new-ip> to restore the data and switch over.
set -euo pipefail
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT="$DIR/secrets/cloud-init.yaml"
ADMIN_USER="${ADMIN_USER:-raul}"
PUBKEY_FILE="${PUBKEY_FILE:-$HOME/.ssh/id_ed25519.pub}"

for f in app.env cloudflared.env ghcr.env; do
    [[ -s "$DIR/secrets/$f" ]] || { echo "Missing deploy/secrets/$f (see the .example files)" >&2; exit 1; }
done
[[ -s "$PUBKEY_FILE" ]] || { echo "No SSH public key at $PUBKEY_FILE (set PUBKEY_FILE=...)" >&2; exit 1; }

stage="$(mktemp -d)"
trap 'rm -rf "$stage"' EXIT
cp -r "$DIR/quadlet" "$stage/"
mkdir "$stage/secrets"
cp "$DIR/secrets/app.env" "$DIR/secrets/cloudflared.env" "$DIR/secrets/ghcr.env" "$stage/secrets/"
cp "$DIR"/{provision.sh,fix-network.sh,harden-server.sh,setup-server.sh,backup.sh,movies-backup.service,movies-backup.timer,podman-auto-update.timer.conf} "$stage/"
cp "$PUBKEY_FILE" "$stage/admin.pub"
echo "ADMIN_USER=$ADMIN_USER" > "$stage/server.conf"
bundle="$(tar -C "$stage" -czf - . | base64 -w0)"

pubkey="$(cat "$PUBKEY_FILE")"
umask 077
{
    cat <<YAML
#cloud-config
# GENERATED by deploy/build-cloud-init.sh on $(date -u +%F). Contains secrets: do not commit or share.
# First boot: fix networking, then unpack the deploy bundle and run provision.sh
# (log: /var/log/movies-provision.log, ends with "PROVISION OK").

users:
  - name: $ADMIN_USER
    groups: [wheel]
    shell: /bin/bash
    sudo: "ALL=(ALL) NOPASSWD:ALL"
    lock_passwd: true
    ssh_authorized_keys:
      - $pubkey

disable_root: true
ssh_pwauth: false

bootcmd:
  - |
YAML
    sed 's/^/    /' "$DIR/fix-network.sh"
    cat <<YAML

write_files:
  - path: /root/movies-deploy.tgz
    permissions: "0600"
    encoding: b64
    content: $bundle

runcmd:
  - [bash, -c, "set -o pipefail; mkdir -p /root/movies-deploy && tar -xzf /root/movies-deploy.tgz -C /root/movies-deploy && bash /root/movies-deploy/provision.sh 2>&1 | tee /var/log/movies-provision.log; rm -rf /root/movies-deploy /root/movies-deploy.tgz /var/lib/cloud/instance/user-data.txt*"]
YAML
} > "$OUT"

echo "Wrote $OUT ($(wc -c < "$OUT") bytes)."
echo "Paste or import it as the server's User Data (Cloud Config), then run: ./deploy/migrate.sh <new-ip>"
